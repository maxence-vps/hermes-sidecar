//! Projects: named folders that group Conversations (Hermes sessions) and the git Repositories
//! they relate to. See `GLOSSARY.md`. They only organise: Hermes knows nothing about them.
//!
//! Stored in the sidecar's database (`migrations/0001_projects.sql`).

use std::collections::HashMap;

use axum::{
    Json,
    extract::{Path, State},
    http::StatusCode,
};
use serde::{Deserialize, Serialize};
use sqlx::SqlitePool;
use utoipa::ToSchema;
use utoipa_axum::{router::OpenApiRouter, routes};
use uuid::Uuid;

use crate::{
    error::{AppError, ErrorBody, JsonBody},
    repository_url,
    state::AppState,
};

/// Longest project name, in characters.
pub const MAX_NAME_CHARS: usize = 100;

/// Tag of the project routes in the OpenAPI spec.
const TAG: &str = "projects";

/// The project routes, to merge into the protected router.
pub fn router() -> OpenApiRouter<AppState> {
    OpenApiRouter::new()
        .routes(routes!(list_projects, create_project))
        .routes(routes!(get_project, rename_project, delete_project))
        .routes(routes!(attach_repository))
        .routes(routes!(detach_repository))
        .routes(routes!(attach_conversation, detach_conversation))
}

/// Longest conversation id, in characters.
pub const MAX_CONVERSATION_ID_LEN: usize = 255;

#[derive(Debug, Serialize, ToSchema)]
pub struct Project {
    /// Generated by the sidecar.
    #[schema(example = "0b7e8f5c-3a3e-4f0e-9a8e-3f1c2d4b5a69")]
    pub id: String,
    #[schema(example = "Hermes")]
    pub name: String,
    /// Sorted by name, ignoring case.
    pub repositories: Vec<Repository>,
    /// Ids of the Hermes sessions in this project, in no guaranteed order.
    #[schema(example = json!(["20260412_101500_ab12cd"]))]
    pub conversation_ids: Vec<String>,
}

/// A git repository attached to a project.
#[derive(Debug, Serialize, ToSchema)]
pub struct Repository {
    /// Generated by the sidecar.
    #[schema(example = "5d1c7a2e-9b0f-4c3d-8e6a-1f2b3c4d5e6f")]
    pub id: String,
    /// Path after the host, derived from the URL.
    #[schema(example = "owner/hermes-sidecar")]
    pub name: String,
    /// Normalised remote URL.
    #[schema(example = "https://github.com/owner/hermes-sidecar")]
    pub url: String,
}

/// Body of `POST /projects` and `PATCH /projects/{id}`.
#[derive(Debug, Deserialize, ToSchema)]
pub struct ProjectInput {
    /// Trimmed, not empty, at most 100 characters, unique ignoring case.
    #[schema(example = "Hermes")]
    pub name: String,
}

/// Body of `POST /projects/{id}/repositories`.
#[derive(Debug, Deserialize, ToSchema)]
pub struct RepositoryInput {
    /// `https://host/owner/name`, `git@host:owner/name` or `ssh://git@host/owner/name`.
    #[schema(example = "git@github.com:owner/hermes-sidecar.git")]
    pub url: String,
}

/// Lists every project, sorted by name ignoring case.
#[utoipa::path(
    get,
    path = "/projects",
    tag = TAG,
    security(("bearer" = [])),
    responses(
        (status = OK, description = "Every project", body = [Project]),
        (status = UNAUTHORIZED, description = "Missing or invalid API key", body = ErrorBody),
    )
)]
async fn list_projects(State(state): State<AppState>) -> Result<Json<Vec<Project>>, AppError> {
    Ok(Json(load_all(&state.db).await?))
}

/// Creates a project.
#[utoipa::path(
    post,
    path = "/projects",
    tag = TAG,
    security(("bearer" = [])),
    request_body = ProjectInput,
    responses(
        (status = CREATED, description = "The new project, with no repository or conversation", body = Project),
        (status = BAD_REQUEST, description = "The body is not JSON (`invalid_body`)", body = ErrorBody),
        (status = UNAUTHORIZED, description = "Missing or invalid API key", body = ErrorBody),
        (status = CONFLICT, description = "Another project has this name, ignoring case (`project_name_taken`)", body = ErrorBody),
        (status = UNPROCESSABLE_ENTITY, description = "Invalid name (`invalid_name`), or no `name` (`invalid_body`)", body = ErrorBody),
    )
)]
async fn create_project(
    State(state): State<AppState>,
    JsonBody(input): JsonBody<ProjectInput>,
) -> Result<(StatusCode, Json<Project>), AppError> {
    let name = validate_name(&input.name)?;
    let id = Uuid::new_v4().to_string();
    sqlx::query("INSERT INTO projects (id, name, name_key) VALUES (?, ?, ?)")
        .bind(&id)
        .bind(name)
        .bind(name_key(name))
        .execute(&state.db)
        .await
        .map_err(name_conflict)?;
    Ok((
        StatusCode::CREATED,
        Json(Project {
            id,
            name: name.to_owned(),
            repositories: Vec::new(),
            conversation_ids: Vec::new(),
        }),
    ))
}

/// Returns a project with its repositories and conversations.
#[utoipa::path(
    get,
    path = "/projects/{id}",
    tag = TAG,
    security(("bearer" = [])),
    params(("id" = String, Path, description = "Project id")),
    responses(
        (status = OK, description = "The project", body = Project),
        (status = UNAUTHORIZED, description = "Missing or invalid API key", body = ErrorBody),
        (status = NOT_FOUND, description = "No project with this id (`project_not_found`)", body = ErrorBody),
    )
)]
async fn get_project(
    State(state): State<AppState>,
    Path(id): Path<String>,
) -> Result<Json<Project>, AppError> {
    let id = parse_id(&id)?;
    Ok(Json(load(&state.db, &id).await?))
}

/// Renames a project. Its own name with a different case is allowed.
#[utoipa::path(
    patch,
    path = "/projects/{id}",
    tag = TAG,
    security(("bearer" = [])),
    params(("id" = String, Path, description = "Project id")),
    request_body = ProjectInput,
    responses(
        (status = OK, description = "The renamed project", body = Project),
        (status = BAD_REQUEST, description = "The body is not JSON (`invalid_body`)", body = ErrorBody),
        (status = UNAUTHORIZED, description = "Missing or invalid API key", body = ErrorBody),
        (status = NOT_FOUND, description = "No project with this id (`project_not_found`)", body = ErrorBody),
        (status = CONFLICT, description = "Another project has this name, ignoring case (`project_name_taken`)", body = ErrorBody),
        (status = UNPROCESSABLE_ENTITY, description = "Invalid name (`invalid_name`), or no `name` (`invalid_body`)", body = ErrorBody),
    )
)]
async fn rename_project(
    State(state): State<AppState>,
    Path(id): Path<String>,
    JsonBody(input): JsonBody<ProjectInput>,
) -> Result<Json<Project>, AppError> {
    let id = parse_id(&id)?;
    let name = validate_name(&input.name)?;
    let updated = sqlx::query("UPDATE projects SET name = ?, name_key = ? WHERE id = ?")
        .bind(name)
        .bind(name_key(name))
        .bind(&id)
        .execute(&state.db)
        .await
        .map_err(name_conflict)?;
    if updated.rows_affected() == 0 {
        return Err(AppError::ProjectNotFound);
    }
    Ok(Json(load(&state.db, &id).await?))
}

/// Deletes a project and its links to repositories and conversations. The conversations stay
/// in Hermes, without a project.
#[utoipa::path(
    delete,
    path = "/projects/{id}",
    tag = TAG,
    security(("bearer" = [])),
    params(("id" = String, Path, description = "Project id")),
    responses(
        (status = NO_CONTENT, description = "Deleted"),
        (status = UNAUTHORIZED, description = "Missing or invalid API key", body = ErrorBody),
        (status = NOT_FOUND, description = "No project with this id (`project_not_found`)", body = ErrorBody),
    )
)]
async fn delete_project(
    State(state): State<AppState>,
    Path(id): Path<String>,
) -> Result<StatusCode, AppError> {
    let id = parse_id(&id)?;
    // The links go with it (ON DELETE CASCADE).
    let deleted = sqlx::query("DELETE FROM projects WHERE id = ?")
        .bind(&id)
        .execute(&state.db)
        .await?;
    if deleted.rows_affected() == 0 {
        return Err(AppError::ProjectNotFound);
    }
    Ok(StatusCode::NO_CONTENT)
}

/// Attaches a git repository to a project.
///
/// The URL is normalised to `https://host/path` (host lowercased, trailing `.git` and `/`
/// removed, path case kept) and the name is the whole path after the host.
#[utoipa::path(
    post,
    path = "/projects/{id}/repositories",
    tag = TAG,
    security(("bearer" = [])),
    params(("id" = String, Path, description = "Project id")),
    request_body = RepositoryInput,
    responses(
        (status = CREATED, description = "The attached repository", body = Repository),
        (status = BAD_REQUEST, description = "The body is not JSON (`invalid_body`)", body = ErrorBody),
        (status = UNAUTHORIZED, description = "Missing or invalid API key", body = ErrorBody),
        (status = NOT_FOUND, description = "No project with this id (`project_not_found`)", body = ErrorBody),
        (status = CONFLICT, description = "The project already has this repository, after normalisation (`repository_already_attached`)", body = ErrorBody),
        (status = UNPROCESSABLE_ENTITY, description = "Unsupported URL (`invalid_repository_url`), or no `url` (`invalid_body`)", body = ErrorBody),
    )
)]
async fn attach_repository(
    State(state): State<AppState>,
    Path(project_id): Path<String>,
    JsonBody(input): JsonBody<RepositoryInput>,
) -> Result<(StatusCode, Json<Repository>), AppError> {
    let project_id = parse_id(&project_id)?;
    ensure_exists(&state.db, &project_id).await?;
    let normalised = repository_url::normalise(&input.url)?;
    let id = Uuid::new_v4().to_string();
    sqlx::query("INSERT INTO project_repositories (id, project_id, url, name) VALUES (?, ?, ?, ?)")
        .bind(&id)
        .bind(&project_id)
        .bind(&normalised.url)
        .bind(&normalised.name)
        .execute(&state.db)
        .await
        .map_err(|error| match &error {
            sqlx::Error::Database(db) if db.is_unique_violation() => {
                AppError::RepositoryAlreadyAttached
            }
            // The project was deleted in the meantime.
            sqlx::Error::Database(db) if db.is_foreign_key_violation() => AppError::ProjectNotFound,
            _ => error.into(),
        })?;
    Ok((
        StatusCode::CREATED,
        Json(Repository {
            id,
            name: normalised.name,
            url: normalised.url,
        }),
    ))
}

/// Detaches a repository from a project.
#[utoipa::path(
    delete,
    path = "/projects/{id}/repositories/{repository_id}",
    tag = TAG,
    security(("bearer" = [])),
    params(
        ("id" = String, Path, description = "Project id"),
        ("repository_id" = String, Path, description = "Repository id, from the project's `repositories`"),
    ),
    responses(
        (status = NO_CONTENT, description = "Detached"),
        (status = UNAUTHORIZED, description = "Missing or invalid API key", body = ErrorBody),
        (status = NOT_FOUND, description = "No project with this id (`project_not_found`), or no repository with this id in it (`repository_not_found`)", body = ErrorBody),
    )
)]
async fn detach_repository(
    State(state): State<AppState>,
    Path((project_id, repository_id)): Path<(String, String)>,
) -> Result<StatusCode, AppError> {
    let project_id = parse_id(&project_id)?;
    ensure_exists(&state.db, &project_id).await?;
    let repository_id = Uuid::try_parse(&repository_id)
        .map_err(|_| AppError::RepositoryNotFound)?
        .to_string();
    let deleted = sqlx::query("DELETE FROM project_repositories WHERE id = ? AND project_id = ?")
        .bind(&repository_id)
        .bind(&project_id)
        .execute(&state.db)
        .await?;
    if deleted.rows_affected() == 0 {
        return Err(AppError::RepositoryNotFound);
    }
    Ok(StatusCode::NO_CONTENT)
}

/// Puts a conversation in a project. A conversation in another project moves to this one.
///
/// The sidecar does not check that the conversation exists in Hermes.
#[utoipa::path(
    put,
    path = "/projects/{id}/conversations/{conversation_id}",
    tag = TAG,
    security(("bearer" = [])),
    params(
        ("id" = String, Path, description = "Project id"),
        ("conversation_id" = String, Path, description = "Hermes session id", example = "20260412_101500_ab12cd"),
    ),
    responses(
        (status = NO_CONTENT, description = "The conversation is in this project, whether it was already or not"),
        (status = UNAUTHORIZED, description = "Missing or invalid API key", body = ErrorBody),
        (status = NOT_FOUND, description = "No project with this id (`project_not_found`)", body = ErrorBody),
        (status = UNPROCESSABLE_ENTITY, description = "Invalid conversation id (`invalid_conversation_id`)", body = ErrorBody),
    )
)]
async fn attach_conversation(
    State(state): State<AppState>,
    Path((project_id, conversation_id)): Path<(String, String)>,
) -> Result<StatusCode, AppError> {
    let project_id = parse_id(&project_id)?;
    ensure_exists(&state.db, &project_id).await?;
    validate_conversation_id(&conversation_id)?;
    sqlx::query(
        "INSERT INTO project_conversations (conversation_id, project_id) VALUES (?, ?) \
         ON CONFLICT (conversation_id) DO UPDATE SET project_id = excluded.project_id",
    )
    .bind(&conversation_id)
    .bind(&project_id)
    .execute(&state.db)
    .await
    .map_err(|error| match &error {
        // The project was deleted in the meantime.
        sqlx::Error::Database(db) if db.is_foreign_key_violation() => AppError::ProjectNotFound,
        _ => error.into(),
    })?;
    Ok(StatusCode::NO_CONTENT)
}

/// Takes a conversation out of a project. Succeeds also when it was not in this project, and
/// then changes nothing.
#[utoipa::path(
    delete,
    path = "/projects/{id}/conversations/{conversation_id}",
    tag = TAG,
    security(("bearer" = [])),
    params(
        ("id" = String, Path, description = "Project id"),
        ("conversation_id" = String, Path, description = "Hermes session id", example = "20260412_101500_ab12cd"),
    ),
    responses(
        (status = NO_CONTENT, description = "The conversation is not in this project"),
        (status = UNAUTHORIZED, description = "Missing or invalid API key", body = ErrorBody),
        (status = NOT_FOUND, description = "No project with this id (`project_not_found`)", body = ErrorBody),
        (status = UNPROCESSABLE_ENTITY, description = "Invalid conversation id (`invalid_conversation_id`)", body = ErrorBody),
    )
)]
async fn detach_conversation(
    State(state): State<AppState>,
    Path((project_id, conversation_id)): Path<(String, String)>,
) -> Result<StatusCode, AppError> {
    let project_id = parse_id(&project_id)?;
    ensure_exists(&state.db, &project_id).await?;
    validate_conversation_id(&conversation_id)?;
    // Only from this project: a conversation that moved elsewhere stays there.
    sqlx::query("DELETE FROM project_conversations WHERE conversation_id = ? AND project_id = ?")
        .bind(&conversation_id)
        .bind(&project_id)
        .execute(&state.db)
        .await?;
    Ok(StatusCode::NO_CONTENT)
}

/// Not empty, at most 255 characters, printable ASCII without spaces, no `/` (which a client
/// could still send percent-encoded).
fn validate_conversation_id(id: &str) -> Result<(), AppError> {
    let valid = !id.is_empty()
        && id.len() <= MAX_CONVERSATION_ID_LEN
        && id.bytes().all(|b| b.is_ascii_graphic() && b != b'/');
    valid.then_some(()).ok_or(AppError::InvalidConversationId)
}

/// Returns the id as stored (lowercase hyphenated UUID). Anything else cannot name a project.
fn parse_id(id: &str) -> Result<String, AppError> {
    Uuid::try_parse(id)
        .map(|id| id.to_string())
        .map_err(|_| AppError::ProjectNotFound)
}

/// Fails with `project_not_found` unless the project exists.
async fn ensure_exists(db: &SqlitePool, id: &str) -> Result<(), AppError> {
    let found: Option<i64> = sqlx::query_scalar("SELECT 1 FROM projects WHERE id = ?")
        .bind(id)
        .fetch_optional(db)
        .await?;
    found.map(|_| ()).ok_or(AppError::ProjectNotFound)
}

/// Trims the name and checks it.
fn validate_name(name: &str) -> Result<&str, AppError> {
    let name = name.trim();
    if name.is_empty() {
        return Err(AppError::InvalidName("the name must not be empty"));
    }
    if name.chars().count() > MAX_NAME_CHARS {
        return Err(AppError::InvalidName(
            "the name must be at most 100 characters",
        ));
    }
    Ok(name)
}

/// What names are compared on: unique ignoring case, Unicode included.
fn name_key(name: &str) -> String {
    name.to_lowercase()
}

/// Turns the unique violation on `name_key` into `project_name_taken`.
fn name_conflict(error: sqlx::Error) -> AppError {
    match &error {
        sqlx::Error::Database(db) if db.is_unique_violation() => AppError::ProjectNameTaken,
        _ => error.into(),
    }
}

async fn load(db: &SqlitePool, id: &str) -> Result<Project, AppError> {
    let name: String = sqlx::query_scalar("SELECT name FROM projects WHERE id = ?")
        .bind(id)
        .fetch_optional(db)
        .await?
        .ok_or(AppError::ProjectNotFound)?;
    let repositories = sqlx::query_as(
        "SELECT id, name, url FROM project_repositories WHERE project_id = ? \
         ORDER BY lower(name), name, id",
    )
    .bind(id)
    .fetch_all(db)
    .await?
    .into_iter()
    .map(|(id, name, url)| Repository { id, name, url })
    .collect();
    let conversation_ids = sqlx::query_scalar(
        "SELECT conversation_id FROM project_conversations WHERE project_id = ?",
    )
    .bind(id)
    .fetch_all(db)
    .await?;
    Ok(Project {
        id: id.to_owned(),
        name,
        repositories,
        conversation_ids,
    })
}

async fn load_all(db: &SqlitePool) -> Result<Vec<Project>, AppError> {
    // One read transaction, so the three queries see the same data.
    let mut tx = db.begin().await?;
    let projects: Vec<(String, String)> =
        sqlx::query_as("SELECT id, name FROM projects ORDER BY name_key, id")
            .fetch_all(&mut *tx)
            .await?;
    let repositories: Vec<(String, String, String, String)> = sqlx::query_as(
        "SELECT project_id, id, name, url FROM project_repositories ORDER BY lower(name), name, id",
    )
    .fetch_all(&mut *tx)
    .await?;
    let conversations: Vec<(String, String)> =
        sqlx::query_as("SELECT project_id, conversation_id FROM project_conversations")
            .fetch_all(&mut *tx)
            .await?;
    tx.commit().await?;

    let mut repositories_by_project: HashMap<String, Vec<Repository>> = HashMap::new();
    for (project_id, id, name, url) in repositories {
        repositories_by_project
            .entry(project_id)
            .or_default()
            .push(Repository { id, name, url });
    }
    let mut conversations_by_project: HashMap<String, Vec<String>> = HashMap::new();
    for (project_id, conversation_id) in conversations {
        conversations_by_project
            .entry(project_id)
            .or_default()
            .push(conversation_id);
    }
    Ok(projects
        .into_iter()
        .map(|(id, name)| Project {
            repositories: repositories_by_project.remove(&id).unwrap_or_default(),
            conversation_ids: conversations_by_project.remove(&id).unwrap_or_default(),
            id,
            name,
        })
        .collect())
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn trims_and_checks_the_name() {
        assert_eq!(validate_name("  Hermes \n").unwrap(), "Hermes");
        assert_eq!(validate_name(&"é".repeat(100)).unwrap(), "é".repeat(100));
        assert!(matches!(
            validate_name("   "),
            Err(AppError::InvalidName(_))
        ));
        assert!(matches!(
            validate_name(&"a".repeat(101)),
            Err(AppError::InvalidName(_))
        ));
    }

    #[test]
    fn compares_names_ignoring_case_beyond_ascii() {
        assert_eq!(name_key("Équipe"), name_key("éQUIPE"));
    }

    #[test]
    fn checks_conversation_ids() {
        for id in ["20260412_101500_ab12cd", "a", &"x".repeat(255), "a.b-c:d~e"] {
            assert!(validate_conversation_id(id).is_ok(), "{id:?}");
        }
        for id in ["", &"x".repeat(256), "a/b", "a b", "é", "a\tb", "a\u{7f}"] {
            assert!(validate_conversation_id(id).is_err(), "{id:?}");
        }
    }

    #[test]
    fn only_a_uuid_can_name_a_project() {
        let id = Uuid::new_v4().to_string();
        assert_eq!(parse_id(&id.to_uppercase()).unwrap(), id);
        assert!(matches!(parse_id("nope"), Err(AppError::ProjectNotFound)));
    }
}
